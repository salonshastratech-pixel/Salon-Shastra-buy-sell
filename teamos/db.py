"""Thin database layer: connection per request, portable SQL, file-based migrations.

Design choice: plain SQL + a small helper instead of an ORM. Migrations are reviewable
.sql files; queries are explicit. SQLite is used for development/tests; PostgreSQL is
the production target (adapter path marked below — requires `psycopg` to be installed
and has NOT yet been exercised in this environment).
"""
from __future__ import annotations

import hashlib
import os
import re
import sqlite3
from decimal import Decimal
from pathlib import Path
from typing import Any, Iterable

from flask import current_app, g

from .timeutil import now_iso

# Portability harness: when TEAMOS_SQL_LOG is set, every statement is appended as JSON so
# scripts/pg_replay.py can replay the exact workload against PostgreSQL.
_SQL_LOG = os.environ.get("TEAMOS_SQL_LOG")


def _log_sql(url, sql, params):
    import json
    with open(_SQL_LOG, "a", encoding="utf-8") as fh:
        fh.write(json.dumps({"db": url, "sql": sql, "params": list(params)}, default=str) + "\n")


# Portability audit: when TEAMOS_SQL_SHAPES is set, each distinct statement is written once (with sample
# parameters), and any result with two columns of the same name is flagged — SQLite keeps the first such
# column and PostgreSQL the last, so those queries must use distinct names (scripts/qa/pg_check.py).
_SQL_SHAPES = os.environ.get("TEAMOS_SQL_SHAPES")
_seen_shapes: set = set()


def _shape(sql, params, cursor=None):
    import json
    key = sql
    dup = None
    if cursor is not None and cursor.description:
        names = [d[0] for d in cursor.description]
        dups = sorted({n for n in names if names.count(n) > 1})
        dup = dups or None
        key = sql + ("|DUP" if dup else "")
    if key in _seen_shapes:
        return
    _seen_shapes.add(key)
    with open(_SQL_SHAPES, "a", encoding="utf-8") as fh:
        fh.write(json.dumps({"sql": sql, "params": list(params), "dup": dup}, default=str) + "\n")


MIGRATIONS_DIR = Path(__file__).resolve().parent.parent / "migrations"

ID_TYPES = {
    "sqlite": "INTEGER PRIMARY KEY AUTOINCREMENT",
    "postgres": "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
}


class Database:
    def __init__(self, url: str, conn=None):
        self.url = url
        self.pooled = False
        if conn is not None:  # a pooled PostgreSQL connection being reused
            self.dialect, self.conn, self.pooled = "postgres", conn, True
        elif url.startswith("sqlite:///"):
            self.dialect = "sqlite"
            path = url[len("sqlite:///"):]
            if path != ":memory:":
                Path(path).parent.mkdir(parents=True, exist_ok=True)
            self.conn = sqlite3.connect(path, detect_types=0, isolation_level=None)
            self.conn.row_factory = sqlite3.Row
            self.conn.execute("PRAGMA foreign_keys = ON")
            self.conn.execute("PRAGMA journal_mode = WAL")
            self.conn.execute("PRAGMA busy_timeout = 5000")
        elif url.startswith(("postgresql://", "postgres://")):
            # PostgreSQL (e.g. Supabase). Every query the app runs is checked against PostgreSQL by
            # scripts/qa/pg_check.py; see docs/SUPABASE.md.
            import psycopg  # type: ignore
            from psycopg.rows import dict_row  # type: ignore

            self.dialect = "postgres"
            extra = {}
            local = any(h in url for h in ("@localhost", "@127.0.0.1", "@[::1]"))
            if "sslmode=" not in url and not local:
                extra["sslmode"] = "require"  # hosted databases: always encrypted
            # prepare_threshold=None: Supabase's connection pooler (and PgBouncer) do not support
            # server-side prepared statements; plain statements work everywhere.
            self.conn = psycopg.connect(safe_pg_url(url), autocommit=True, row_factory=dict_row, prepare_threshold=None,
                                        connect_timeout=15, application_name="teamos", **extra)
        else:
            raise ValueError("Unsupported DATABASE_URL: " + url)
        self._tx_depth = 0
        self._after_commit = []

    def after_commit(self, fn) -> None:
        """Run fn() once the current transaction has committed (at once when none is open; dropped on rollback)."""
        if self._tx_depth == 0:
            fn()
        else:
            self._after_commit.append(fn)

    # -- SQL helpers -------------------------------------------------------
    def _sql(self, sql: str) -> str:
        if self.dialect == "postgres":
            # psycopg uses %s placeholders, so a literal % (e.g. LIKE 'x%') must be doubled first.
            return sql.replace("%", "%%").replace("?", "%s")
        return sql

    def execute(self, sql: str, params: Iterable[Any] = ()):
        params = tuple(params)
        if _SQL_LOG:
            _log_sql(self.url, sql, params)
        cur = self.conn.execute(self._sql(sql), params)
        if _SQL_SHAPES:
            _shape(sql, params, cur)
        return cur

    def _row(self, r) -> dict:
        d = dict(r)
        if self.dialect == "postgres":  # SUM/AVG come back as Decimal on PostgreSQL; the app works in int/float
            for k, v in d.items():
                if isinstance(v, Decimal):
                    d[k] = int(v) if v == v.to_integral_value() else float(v)
        return d

    def all(self, sql: str, params: Iterable[Any] = ()) -> list[dict]:
        return [self._row(r) for r in self.execute(sql, params).fetchall()]

    def one(self, sql: str, params: Iterable[Any] = ()) -> dict | None:
        row = self.execute(sql, params).fetchone()
        return self._row(row) if row is not None else None

    def scalar(self, sql: str, params: Iterable[Any] = ()):
        row = self.execute(sql, params).fetchone()
        if row is None:
            return None
        return list(self._row(row).values())[0]

    def insert(self, table: str, values: dict) -> int:
        cols = ", ".join(values.keys())
        marks = ", ".join("?" for _ in values)
        sql = f"INSERT INTO {table} ({cols}) VALUES ({marks})"
        if self.dialect == "postgres":
            # RETURNING * also works for tables keyed without an id column (field_provenance, buyer_preferences …)
            row = self.execute(sql + " RETURNING *", values.values()).fetchone()
            return row.get("id") if row else None
        return self.execute(sql, values.values()).lastrowid

    def update(self, table: str, row_id: int, values: dict) -> None:
        if not values:
            return
        sets = ", ".join(f"{k} = ?" for k in values)
        self.execute(f"UPDATE {table} SET {sets} WHERE id = ?", [*values.values(), row_id])

    # -- transactions (re-entrant) -----------------------------------------
    def __enter__(self):
        if self._tx_depth == 0:
            self.execute("BEGIN")
        self._tx_depth += 1
        return self

    def __exit__(self, exc_type, exc, tb):
        self._tx_depth -= 1
        if self._tx_depth == 0:
            self.execute("ROLLBACK" if exc_type else "COMMIT")
            pending, self._after_commit = self._after_commit, []
            if not exc_type:
                for fn in pending:
                    fn()
        return False

    def close(self):
        self.conn.close()


# -- PostgreSQL connection reuse ------------------------------------------------------------------------------
# Opening an encrypted connection to a hosted database (Supabase) costs several network round trips — about half a
# second from Render Singapore to Supabase Mumbai. Each server process keeps a few idle connections and reuses them.
# A connection idle for more than a minute is checked before reuse (the pooler may have dropped it); one that is in
# the middle of a transaction, or broken, is closed instead of being reused.
import threading as _threading  # noqa: E402
import time as _time  # noqa: E402

_POOL: dict[str, list] = {}
_POOL_LOCK = _threading.Lock()
POOL_MAX = int(os.environ.get("DB_POOL_MAX", "6"))
POOL_RECHECK_SECONDS = 60


def safe_pg_url(url: str) -> str:
    """Database addresses whose password contains @ : / ? # % break URL parsing. Encode the password part (between
    '://user:' and the LAST '@'), leaving already-encoded addresses unchanged."""
    from urllib.parse import quote, unquote
    m = re.match(r"^(postgres(?:ql)?://)([^:/@]+):(.*)@([^@]+)$", url or "")
    if not m:
        return url
    scheme, user, pw, rest = m.groups()
    return f"{scheme}{user}:{quote(unquote(pw), safe='')}@{rest}"


def _take_pg(url: str):
    while True:
        with _POOL_LOCK:
            idle = _POOL.get(url) or []
            item = idle.pop() if idle else None
        if item is None:
            return None
        conn, last_used = item
        try:
            if conn.closed:
                continue
            if _time.monotonic() - last_used > POOL_RECHECK_SECONDS:
                conn.execute("SELECT 1")
            return conn
        except Exception:  # noqa: BLE001 — a dropped connection: discard and try the next one / a new one
            try:
                conn.close()
            except Exception:  # noqa: BLE001
                pass


def _give_pg(db: "Database") -> None:
    conn = db.conn
    try:
        import psycopg  # type: ignore
        ok = (not conn.closed and db._tx_depth == 0
              and conn.info.transaction_status == psycopg.pq.TransactionStatus.IDLE)
    except Exception:  # noqa: BLE001
        ok = False
    if ok:
        with _POOL_LOCK:
            idle = _POOL.setdefault(db.url, [])
            if len(idle) < POOL_MAX:
                idle.append((conn, _time.monotonic()))
                return
    conn.close()


def get_db() -> Database:
    if "db" not in g:
        url = current_app.config["DATABASE_URL"]
        conn = _take_pg(url) if url.startswith(("postgresql://", "postgres://")) else None
        g.db = Database(url, conn=conn) if conn is not None else Database(url)
    return g.db


def close_db(_exc=None):
    db = g.pop("db", None)
    if db is None:
        return
    if db.dialect == "postgres":
        _give_pg(db)
    else:
        db.close()


# -- migrations -----------------------------------------------------------------
def _split_statements(sql: str) -> list[str]:
    sql = re.sub(r"--[^\n]*", "", sql)
    return [s.strip() for s in sql.split(";") if s.strip()]


def migrate(db: Database) -> list[str]:
    db.execute(
        "CREATE TABLE IF NOT EXISTS schema_migrations (version TEXT PRIMARY KEY, checksum TEXT NOT NULL, applied_at TEXT NOT NULL)"
    )
    applied = {r["version"]: r["checksum"] for r in db.all("SELECT version, checksum FROM schema_migrations")}
    done = []
    for path in sorted(MIGRATIONS_DIR.glob("*.sql")):
        raw = path.read_text(encoding="utf-8")
        checksum = hashlib.sha256(raw.encode()).hexdigest()
        if path.stem in applied:
            if applied[path.stem] != checksum:
                raise RuntimeError(f"Migration {path.name} was edited after being applied. Add a new migration instead.")
            continue
        sql = raw.replace("{{ID}}", ID_TYPES[db.dialect])
        with db:
            for stmt in _split_statements(sql):
                if stmt.startswith("/*pg*/"):
                    if db.dialect != "postgres":
                        continue  # PostgreSQL-only (e.g. row-level security on Supabase)
                    stmt = stmt[len("/*pg*/"):].strip()
                db.execute(stmt)
            db.execute(
                "INSERT INTO schema_migrations (version, checksum, applied_at) VALUES (?, ?, ?)",
                (path.stem, checksum, now_iso()),
            )
        done.append(path.name)
    return done


def open_standalone(url: str | None = None) -> Database:
    return Database(url or os.environ.get("DATABASE_URL", "sqlite:///instance/teamos.db"))
