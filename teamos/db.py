"""Thin database layer: connection per request, portable SQL, file-based migrations.

Design choice: plain SQL + a small helper instead of an ORM. Migrations are reviewable
.sql files; queries are explicit. SQLite is used for development/tests; PostgreSQL is
the production target (adapter path marked below — requires `psycopg` to be installed
and has NOT yet been exercised in this environment).
"""
from __future__ import annotations

import hashlib
import os
import re
import sqlite3
from pathlib import Path
from typing import Any, Iterable

from flask import current_app, g

from .timeutil import now_iso

# Portability harness: when TEAMOS_SQL_LOG is set, every statement is appended as JSON so
# scripts/pg_replay.py can replay the exact workload against PostgreSQL.
_SQL_LOG = os.environ.get("TEAMOS_SQL_LOG")


def _log_sql(url, sql, params):
    import json
    with open(_SQL_LOG, "a", encoding="utf-8") as fh:
        fh.write(json.dumps({"db": url, "sql": sql, "params": list(params)}, default=str) + "\n")


MIGRATIONS_DIR = Path(__file__).resolve().parent.parent / "migrations"

ID_TYPES = {
    "sqlite": "INTEGER PRIMARY KEY AUTOINCREMENT",
    "postgres": "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
}


class Database:
    def __init__(self, url: str):
        self.url = url
        if url.startswith("sqlite:///"):
            self.dialect = "sqlite"
            path = url[len("sqlite:///"):]
            if path != ":memory:":
                Path(path).parent.mkdir(parents=True, exist_ok=True)
            self.conn = sqlite3.connect(path, detect_types=0, isolation_level=None)
            self.conn.row_factory = sqlite3.Row
            self.conn.execute("PRAGMA foreign_keys = ON")
            self.conn.execute("PRAGMA journal_mode = WAL")
            self.conn.execute("PRAGMA busy_timeout = 5000")
        elif url.startswith("postgresql://"):
            # PostgreSQL path — UNTESTED here (driver not installable offline). See docs/STATUS.md.
            import psycopg  # type: ignore
            from psycopg.rows import dict_row  # type: ignore

            self.dialect = "postgres"
            self.conn = psycopg.connect(url, autocommit=True, row_factory=dict_row)
        else:
            raise ValueError("Unsupported DATABASE_URL: " + url)
        self._tx_depth = 0

    # -- SQL helpers -------------------------------------------------------
    def _sql(self, sql: str) -> str:
        if self.dialect == "postgres":
            return sql.replace("?", "%s")
        return sql

    def execute(self, sql: str, params: Iterable[Any] = ()):
        params = tuple(params)
        if _SQL_LOG:
            _log_sql(self.url, sql, params)
        return self.conn.execute(self._sql(sql), params)

    def all(self, sql: str, params: Iterable[Any] = ()) -> list[dict]:
        return [dict(r) for r in self.execute(sql, params).fetchall()]

    def one(self, sql: str, params: Iterable[Any] = ()) -> dict | None:
        row = self.execute(sql, params).fetchone()
        return dict(row) if row is not None else None

    def scalar(self, sql: str, params: Iterable[Any] = ()):
        row = self.execute(sql, params).fetchone()
        if row is None:
            return None
        return list(dict(row).values())[0]

    def insert(self, table: str, values: dict) -> int:
        cols = ", ".join(values.keys())
        marks = ", ".join("?" for _ in values)
        sql = f"INSERT INTO {table} ({cols}) VALUES ({marks})"
        if self.dialect == "postgres":
            return self.execute(sql + " RETURNING id", values.values()).fetchone()["id"]
        return self.execute(sql, values.values()).lastrowid

    def update(self, table: str, row_id: int, values: dict) -> None:
        if not values:
            return
        sets = ", ".join(f"{k} = ?" for k in values)
        self.execute(f"UPDATE {table} SET {sets} WHERE id = ?", [*values.values(), row_id])

    # -- transactions (re-entrant) -----------------------------------------
    def __enter__(self):
        if self._tx_depth == 0:
            self.execute("BEGIN")
        self._tx_depth += 1
        return self

    def __exit__(self, exc_type, exc, tb):
        self._tx_depth -= 1
        if self._tx_depth == 0:
            self.execute("ROLLBACK" if exc_type else "COMMIT")
        return False

    def close(self):
        self.conn.close()


def get_db() -> Database:
    if "db" not in g:
        g.db = Database(current_app.config["DATABASE_URL"])
    return g.db


def close_db(_exc=None):
    db = g.pop("db", None)
    if db is not None:
        db.close()


# -- migrations -----------------------------------------------------------------
def _split_statements(sql: str) -> list[str]:
    sql = re.sub(r"--[^\n]*", "", sql)
    return [s.strip() for s in sql.split(";") if s.strip()]


def migrate(db: Database) -> list[str]:
    db.execute(
        "CREATE TABLE IF NOT EXISTS schema_migrations (version TEXT PRIMARY KEY, checksum TEXT NOT NULL, applied_at TEXT NOT NULL)"
    )
    applied = {r["version"]: r["checksum"] for r in db.all("SELECT version, checksum FROM schema_migrations")}
    done = []
    for path in sorted(MIGRATIONS_DIR.glob("*.sql")):
        raw = path.read_text(encoding="utf-8")
        checksum = hashlib.sha256(raw.encode()).hexdigest()
        if path.stem in applied:
            if applied[path.stem] != checksum:
                raise RuntimeError(f"Migration {path.name} was edited after being applied. Add a new migration instead.")
            continue
        sql = raw.replace("{{ID}}", ID_TYPES[db.dialect])
        with db:
            for stmt in _split_statements(sql):
                db.execute(stmt)
            db.execute(
                "INSERT INTO schema_migrations (version, checksum, applied_at) VALUES (?, ?, ?)",
                (path.stem, checksum, now_iso()),
            )
        done.append(path.name)
    return done


def open_standalone(url: str | None = None) -> Database:
    return Database(url or os.environ.get("DATABASE_URL", "sqlite:///instance/teamos.db"))
