TE = {_norm(k): v for k, v in TE_RAW.items()}


def tr(text, lang: str | None) -> str:
    """Translate a customer-facing English string (falls back to the English text)."""
    if not text or lang != "te":
        return text
    return TE.get(_norm(str(text)), text)


def pick(request) -> str:
    """Language for this customer: ?lang= on the link, then the form field, then the browser, else English."""
    for v in (request.args.get("lang"), request.form.get("lang") if request.method == "POST" else None,
              request.cookies.get("form_lang")):
        if v in LANGS:
            return v
    al = (request.headers.get("Accept-Language") or "").lower()
    return "te" if al.startswith("te") else "en"


def missing(strings) -> list[str]:
    """English strings with no Telugu yet (used by a test so new questions don't silently stay English)."""
    return [s for s in strings if s and _norm(s) not in TE]
