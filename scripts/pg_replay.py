"""Replay a logged SQLite workload against PostgreSQL to prove query portability.

Usage: TEAMOS_SQL_LOG=/tmp/sql.jsonl python3 -m pytest
       python3 scripts/pg_replay.py /tmp/sql.jsonl  (needs local `psql` and a superuser)
Each test database becomes a fresh PG schema; migrations are applied, then every DML/query is
replayed in order through psql with ON_ERROR_STOP. Identity sequences are re-aligned after ROLLBACK
because SQLite AUTOINCREMENT does not consume ids in rolled-back transactions while PG sequences do.
"""
import json
import re
import subprocess
import sys
from collections import OrderedDict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PG_ID = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"


def lit(v):
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "1" if v else "0"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def inline(sql, params):
    out, i = [], 0
    for part in re.split(r"(\?)", sql):
        if part == "?":
            out.append(lit(params[i]))
            i += 1
        else:
            out.append(part)
    assert i == len(params), sql
    return "".join(out)


def migrations_sql():
    parts = []
    for p in sorted((ROOT / "migrations").glob("*.sql")):
        parts.append(p.read_text().replace("{{ID}}", PG_ID))
    return "\n".join(parts)


TABLES_WITH_ID = None


def realign():
    return ("DO $$ DECLARE r record; BEGIN FOR r IN SELECT table_name FROM information_schema.columns "
            "WHERE table_schema = current_schema() AND column_name = 'id' AND is_identity = 'YES' LOOP "
            "EXECUTE format('SELECT setval(pg_get_serial_sequence(%L, ''id''), COALESCE((SELECT max(id) FROM %I), 0) + 1, false)', "
            "r.table_name, r.table_name); END LOOP; END $$;")


def main(path):
    groups = OrderedDict()
    for line in open(path, encoding="utf-8"):
        e = json.loads(line)
        groups.setdefault(e["db"], []).append(e)
    total, failed = 0, []
    for n, (db, entries) in enumerate(groups.items()):
        schema = f"t{n}"
        stmts = [f"DROP SCHEMA IF EXISTS {schema} CASCADE;", f"CREATE SCHEMA {schema};", f"SET search_path TO {schema};",
                 migrations_sql()]
        for e in entries:
            sql = e["sql"].strip()
            up = sql.upper()
            if up.startswith(("PRAGMA", "CREATE ", "ALTER TABLE")) or "SCHEMA_MIGRATIONS" in up:
                continue
            stmts.append(inline(sql, e["params"]) + ";")
            total += 1
            if up == "ROLLBACK":
                stmts.append(realign())
        stmts.append(f"SET search_path TO public; DROP SCHEMA {schema} CASCADE;")
        r = subprocess.run(["su", "postgres", "-c", "psql -q -v ON_ERROR_STOP=1 -d postgres"],
                           input="\n".join(stmts), capture_output=True, text=True)
        if r.returncode != 0:
            failed.append((db, r.stderr.strip()[:1500]))
    print(f"Replayed {total} statements from {len(groups)} test databases on PostgreSQL.")
    if failed:
        for db, err in failed[:5]:
            print("FAILED", db, "\n", err)
        sys.exit(1)
    print("All statements executed successfully on PostgreSQL.")


if __name__ == "__main__":
    main(sys.argv[1])
